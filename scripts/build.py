#!/usr/bin/env python3
"""Inline the shared ``src/open_webui_tenki`` core into self-contained plugin files.

Open WebUI's one-click hub import expects each plugin to be a single file with no
local package dependency. This script concatenates the core modules (in dependency
order) plus an entry module into one file, stripping intra-package imports, hoisting
and de-duplicating external imports, and prepending the discovery/frontmatter block.

Run: ``python scripts/build.py`` → writes the files under ``open-webui/``.
"""

from __future__ import annotations

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / "src" / "open_webui_tenki"

# Core modules inlined into every distributable, in dependency order.
CORE_MODULES = ["constants", "config", "result", "languages", "core"]

TOOL_FRONTMATTER = '''\
"""
title: Tenki Sandbox
author: LuxorLabs
author_url: https://github.com/LuxorLabs/open-webui-tenki
funding_url: https://github.com/LuxorLabs/open-webui-tenki
description: Run Python and shell code in isolated, ephemeral Tenki microVM sandboxes. A secure code interpreter / code execution sandbox for Open WebUI (isolated, ephemeral, microVM).
version: 0.1.0
license: MIT
requirements: tenki-sandbox[async]>=0.3.5
"""'''

ACTION_FRONTMATTER = '''\
"""
title: Tenki Sandbox — Run Code
author: LuxorLabs
author_url: https://github.com/LuxorLabs/open-webui-tenki
funding_url: https://github.com/LuxorLabs/open-webui-tenki
description: A "Run code" button that executes a message's Python or shell code block in an isolated, ephemeral Tenki microVM sandbox — a secure code interpreter / code execution sandbox for Open WebUI.
version: 0.1.0
license: MIT
requirements: tenki-sandbox[async]>=0.3.5
"""'''

# (entry_module, frontmatter, output_path)
TARGETS = [
    ("tool", TOOL_FRONTMATTER, ROOT / "open-webui" / "tools" / "tenki_code_execution.py"),
    ("action", ACTION_FRONTMATTER, ROOT / "open-webui" / "functions" / "tenki_run_code.py"),
]


def _is_intra_package(node: ast.ImportFrom) -> bool:
    return node.level > 0 or (node.module or "").startswith("open_webui_tenki")


def _split_module(
    source: str, plain_imports: set[str], from_imports: dict[str, set[str]]
) -> list[str]:
    """Collect a module's external imports (merged into the caller's accumulators)
    and return its body segments (docstring, __future__ and intra-package imports
    stripped)."""
    tree = ast.parse(source)
    docstring = ast.get_docstring(tree, clean=False)
    lines = source.splitlines()

    body: list[str] = []
    for node in tree.body:
        if (
            isinstance(node, ast.Expr)
            and isinstance(node.value, ast.Constant)
            and node.value.value == docstring
        ):
            continue  # module docstring
        if isinstance(node, ast.ImportFrom):
            if node.module == "__future__" or _is_intra_package(node):
                continue
            names = from_imports.setdefault(node.module, set())
            for alias in node.names:
                name = alias.name if alias.asname is None else f"{alias.name} as {alias.asname}"
                names.add(name)
            continue
        if isinstance(node, ast.Import):
            for alias in node.names:
                name = alias.name if alias.asname is None else f"{alias.name} as {alias.asname}"
                plain_imports.add(name)
            continue
        # Slice full source lines from the node's start to its end. Unlike
        # ast.get_source_segment, this includes any decorators (a ClassDef/
        # FunctionDef's lineno points at the `class`/`def`, not its `@decorators`),
        # so `@dataclass` and friends survive inlining.
        start = node.lineno
        decorators = getattr(node, "decorator_list", None)
        if decorators:
            start = min(d.lineno for d in decorators)
        body.append("\n".join(lines[start - 1 : node.end_lineno]))
    return body


def build_target(entry_module: str, frontmatter: str, output_path: Path) -> None:
    plain_imports: set[str] = set()
    from_imports: dict[str, set[str]] = {}
    all_body: list[str] = []

    for name in [*CORE_MODULES, entry_module]:
        source = (PKG / f"{name}.py").read_text()
        all_body.extend(_split_module(source, plain_imports, from_imports))

    import_lines = [f"import {name}" for name in sorted(plain_imports)]
    import_lines += [
        f"from {module} import {', '.join(sorted(names))}"
        for module, names in sorted(from_imports.items())
    ]

    parts = [
        frontmatter,
        "",
        "# ---------------------------------------------------------------------------",
        "# AUTO-GENERATED by scripts/build.py — do not edit directly.",
        "# Source of truth: src/open_webui_tenki/. Rebuild: python scripts/build.py",
        "# ---------------------------------------------------------------------------",
        "",
        "from __future__ import annotations",
        "",
        *sorted(import_lines),
        "",
        "",
        "\n\n\n".join(all_body),
        "",
    ]
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(parts))
    print(f"wrote {output_path.relative_to(ROOT)}")


def main() -> None:
    for entry_module, frontmatter, output_path in TARGETS:
        build_target(entry_module, frontmatter, output_path)


if __name__ == "__main__":
    main()
